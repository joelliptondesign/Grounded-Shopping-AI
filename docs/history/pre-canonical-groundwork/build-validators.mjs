import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const names = readdirSync(new URL('schemas/',root)).filter(n=>n.endsWith('.json')).sort();
const ajv = new Ajv({allErrors:true,strict:false,code:{source:true}});
for (const name of names) ajv.addSchema(JSON.parse(readFileSync(new URL('schemas/'+name,root))));
const ids={'receiptV3':'receipt-v3','receiptV2':'receipt-v2','decision':'decision-summary-v1','guidanceMap':'guidance-map-v1'};
const digest=createHash('sha256').update(JSON.stringify(names.map(n=>[n,readFileSync(new URL('schemas/'+n,root),'utf8')]))).digest('hex');
const result=await build({stdin:{contents:standalone(ajv,ids)+`\nexports.schemaDigest=${JSON.stringify(digest)};`,resolveDir:fileURLToPath(root)},bundle:true,platform:'node',format:'cjs',write:false,minify:false,legalComments:'inline'});
writeFileSync(new URL('validators.cjs',root), '// Generated by npm run build; edit schemas, not this file.\n'+result.outputFiles[0].text.replace(/^\/\/ .*node_modules\/ajv\//gm, '// node_modules/ajv/'));
console.log('Compiled four schema validators.');
